    sentiment: 'Đánh giá / Tâm lý',
    score: 'Điểm số',
    confidence: 'Độ tin cậy',
    key_points: 'Điểm chính',
    keyPoints: 'Điểm chính',
    risks: 'Rủi ro',
    opportunities: 'Cơ hội',
