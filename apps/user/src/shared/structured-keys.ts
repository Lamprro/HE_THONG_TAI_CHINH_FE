    modelVersion: 'Phiên bản mô hình',
    created_at: 'Thời gian tạo',
    createdAt: 'Thời gian tạo',
    published_at: 'Ngày công bố',
    publishedAt: 'Ngày công bố',
    status: 'Trạng thái',
    valid_from: 'Hiệu lực từ',
    validFrom: 'Hiệu lực từ',
    valid_until: 'Hiệu lực đến',
    validUntil: 'Hiệu lực đến',
    assumptions: 'Giả định',
    scenarios: 'Kịch bản',
